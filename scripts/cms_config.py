#!/usr/bin/env python3
"""Build admin/config.yml (Sveltia CMS) from admin/fields.yml and data/destinations.json.

The admin gets one "Sardinia (island)" group plus one group per destination, so each
town's coordinator works in their own section. Run after adding a destination
(scripts/new_destination.py runs it for you).
"""
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
REPO = "blankworker1/travel2sardinia"


class Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True


def file_entry(name, label, path, fields):
    return {"name": name, "label": label, "file": path, "format": "json", "fields": fields}


def build():
    f = yaml.safe_load((ROOT / "admin" / "fields.yml").read_text())
    dests = json.loads((ROOT / "data" / "destinations.json").read_text()).get("destinations", [])

    holiday_fields = f["events"]
    island = {
        "name": "island",
        "label": "Sardinia (island)",
        "editor": {"preview": False},
        "files": [
            file_entry("flights", "Flight routes", "data/flights.json", f["flights"]),
            file_entry("holidays", "Public holidays", "data/holidays.json", holiday_fields),
            file_entry("destinations", "Destinations", "data/destinations.json", f["destinations"]),
            file_entry("info", "Island tips", "data/info.json", f["info"]),
            file_entry("site", "Site settings and links", "data/site.json", f["site"]),
        ],
    }
    collections = [island]
    for d in dests:
        did = d["id"]
        name = (d.get("name") or {}).get("it") or did
        base = f"data/destinations/{did}"
        collections.append({
            "name": f"dest_{did.replace('-', '_')}",
            "label": f"{name} (destination)",
            "editor": {"preview": False},
            "files": [
                file_entry(f"{did}_events", f"{name}: events", f"{base}/events.json", f["events"]),
                file_entry(f"{did}_stays", f"{name}: places to stay", f"{base}/stays.json", f["stays"]),
                file_entry(f"{did}_taxis", f"{name}: taxis and transfers", f"{base}/taxis.json", f["taxis"]),
                file_entry(f"{did}_bikes", f"{name}: bike hire", f"{base}/bikes.json", f["bikes"]),
                file_entry(f"{did}_info", f"{name}: local tips", f"{base}/info.json", f["info"]),
                file_entry(f"{did}_settings", f"{name}: links and coordinator", f"{base}/destination.json", f["destination_settings"]),
            ],
        })

    config = {
        "backend": {"name": "github", "repo": REPO, "branch": "main"},
        "media_folder": "assets/uploads",
        "public_folder": "/assets/uploads",
        "collections": collections,
    }
    header = (
        "# Generated by scripts/cms_config.py from admin/fields.yml and data/destinations.json. Don't edit by hand.\n"
        "# Sign in with a GitHub fine-grained token (Contents: read and write on this repo only).\n"
        "# Every save is a commit; the site redeploys itself.\n"
    )
    (ROOT / "admin" / "config.yml").write_text(header + yaml.dump(config, Dumper=Dumper, sort_keys=False, allow_unicode=True, width=120))
    print(f"admin/config.yml: island + {len(dests)} destination(s)")


if __name__ == "__main__":
    build()
